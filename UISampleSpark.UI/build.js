// Clean the lib directory first
console.log('Cleaning wwwroot/lib directory...');
fs.emptyDirSync(path.resolve(__dirname, 'wwwroot/lib'));

// Copy each library
console.log('Copying library files...');
libraries.forEach(lib => {
  lib.files.forEach(file => {
    const sourcePath = path.resolve(__dirname, lib.source, file);
    const destPath = path.resolve(__dirname, lib.destination, file);
    
    // Make sure the destination directory exists
    fs.ensureDirSync(path.dirname(destPath));
    
    // Copy the file
    try {
      fs.copySync(sourcePath, destPath);
      console.log(`Copied: ${sourcePath} -> ${destPath}`);
    } catch (err) {
      console.error(`Error copying ${sourcePath}: ${err.message}`);
    }
  });
});

console.log('Library build complete!');

// Generate wwwroot/css/icons.css: each icon is a CSS mask filled with
// currentColor, so it inherits text color and font-size in every UI pattern
// (Razor, React, Vue, Blazor, htmx and plain JS templates alike).
const iconDir = path.resolve(__dirname, 'node_modules/lucide-static/icons');
const lucideVersion = require('lucide-static/package.json').version;
const rules = icons.map(name => {
  const svg = fs.readFileSync(path.join(iconDir, `${name}.svg`), 'utf8')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s*class="[^"]*"/, '')
    .replace(/\s+/g, ' ')
    .replace(/> </g, '><')
    .trim();
  const uri = 'data:image/svg+xml,' + encodeURIComponent(svg).replace(/'/g, '%27');
  return `.icon-${name} { --icon: url("${uri}"); }`;
});
const css = `/* Generated by build.js from lucide-static v${lucideVersion} (ISC, see lib/lucide/LICENSE). Do not edit. */
.icon {
  display: inline-block;
  width: 1em;
  height: 1em;
  flex-shrink: 0;
  vertical-align: -0.125em;
  background-color: currentColor;
  -webkit-mask: var(--icon) center / contain no-repeat;
  mask: var(--icon) center / contain no-repeat;
}
${rules.join('\n')}
`;
fs.writeFileSync(path.resolve(__dirname, 'wwwroot/css/icons.css'), css);
console.log(`Generated wwwroot/css/icons.css (${icons.length} Lucide icons)`);