#!/usr/bin/env bash
# BSW.DevSpark - (c) 2026 Baylor Scott & White Health. Source: https://bsw-devspark.bswhive.com
# Generate the Agent Skills for every templates/commands/*.md:
#   - source-repository skills .github/skills/devspark-<command>/SKILL.md, whose body routes
#     directly to templates/commands/<command>.md (the five source-only commands carry the
#     stop body from eng/skills/source-stop/<command>.md instead), and
#   - published consumer skills templates/consumer-skills/devspark-<command>/SKILL.md, thin entry
#     points that resolve the command through the developer > team > default chain.
# No command instructions are copied into a skill.
#
# Exit codes:
#   0 - success (no drift, or skills (re)generated)
#   1 - drift detected with --check (CI gate)
#   2 - I/O failure
set -euo pipefail

CHECK=0
REPO_ROOT=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --check) CHECK=1; shift ;;
    --repo-root) REPO_ROOT="$2"; shift 2 ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done

if [[ -z "$REPO_ROOT" ]]; then
  REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
fi

COMMANDS_DIR="$REPO_ROOT/templates/commands"
STOP_DIR="$REPO_ROOT/eng/skills/source-stop"
SKILLS_DIR="$REPO_ROOT/.github/skills"
CONSUMER_DIR="$REPO_ROOT/templates/consumer-skills"
SOURCE_ONLY_COMMANDS=(add-application discover-constitution list-applications personalize upgrade)

if [[ ! -d "$COMMANDS_DIR" ]]; then
  echo "commands dir not found: $COMMANDS_DIR" >&2
  exit 2
fi

template_description() {
  awk '{ sub(/\r$/, "") } /^description:/ { sub(/^description:[[:space:]]*/, ""); sub(/[[:space:]]+$/, ""); print; exit }' "$1"
}

is_source_only() {
  local c
  for c in "${SOURCE_ONLY_COMMANDS[@]}"; do
    [[ "$c" == "$1" ]] && return 0
  done
  return 1
}

# Source-repository skill: the template description plus either a direct route to the command
# template or, for the source-only commands, the stop body.
source_skill_body() {
  local cmd="$1" description="$2"
  if is_source_only "$cmd"; then
    printf '%s\n' \
      "---" \
      "name: devspark-$cmd" \
      "description: \"$description\"" \
      "user-invocable: true" \
      "disable-model-invocation: true" \
      "---" \
      "" \
      "<!-- Generated by scripts/{bash,powershell}/generate-atomic-shims from templates/commands/$cmd.md (description) and eng/skills/source-stop/$cmd.md (stop). Do not edit; edit the sources and regenerate. -->" \
      "" \
      "$(tr -d '\r' < "$STOP_DIR/$cmd.md")"
  else
    printf '%s\n' \
      "---" \
      "name: devspark-$cmd" \
      "description: \"$description\"" \
      "user-invocable: true" \
      "disable-model-invocation: true" \
      "---" \
      "" \
      "<!-- Generated by scripts/{bash,powershell}/generate-atomic-shims from templates/commands/$cmd.md (description). Do not edit; edit the source and regenerate. -->" \
      "" \
      "Read and follow the instructions in \`templates/commands/$cmd.md\` exactly."
  fi
}

# Published consumer skill: a thin entry point that resolves the command through the
# developer > team > default chain and passes the typed text through as the command input.
consumer_skill_body() {
  local cmd="$1" description="$2"
  cat <<EOF
---
name: devspark-$cmd
description: "$description"
user-invocable: true
disable-model-invocation: true
---

<!-- Generated by BSW.DevSpark. Do not edit. -->

## Prompt Resolution

Determine the current git user by running \`git config user.name\`.
Normalize to a folder-safe slug: lowercase, replace spaces with hyphens, strip non-alphanumeric/hyphen chars.

Read and execute the instructions from the **first file that exists**:

1. \`.devspark.work/{git-user}/commands/devspark.$cmd.md\` (personalized override)
2. \`.devspark.work/commands/devspark.$cmd.md\` (team customization)
3. \`.devspark/defaults/commands/devspark.$cmd.md\` (stock default)

Where \`{git-user}\` is the normalized slug from the step above.

## User Input

The text typed after \`/devspark-$cmd\` is the command input. Pass it unchanged to the resolved prompt.
EOF
}

shopt -s nullglob

# Validate every source before writing anything, so a bad source never leaves partial output.
for f in "$COMMANDS_DIR"/*.md; do
  cmd="$(basename "$f" .md)"
  if [[ -z "$(template_description "$f")" ]]; then
    echo "command template has no description: $f" >&2
    exit 2
  fi
done
for cmd in "${SOURCE_ONLY_COMMANDS[@]}"; do
  if [[ -f "$COMMANDS_DIR/$cmd.md" && ! -f "$STOP_DIR/$cmd.md" ]]; then
    echo "missing source-only stop body: $STOP_DIR/$cmd.md" >&2
    exit 2
  fi
done

skill_drift=()
consumer_drift=()
orphans=()
consumer_orphans=()
skills_generated=0
consumer_generated=0

for f in "$COMMANDS_DIR"/*.md; do
  cmd="$(basename "$f" .md)"

  description="$(template_description "$f")"
  description="${description//\\/\\\\}"
  description="${description//\"/\\\"}"
  skill="$SKILLS_DIR/devspark-$cmd/SKILL.md"
  skill_body="$(source_skill_body "$cmd" "$description")"

  if [[ ! -f "$skill" ]] || ! cmp -s <(printf "%s\n" "$skill_body") "$skill"; then
    skill_drift+=("devspark-$cmd")
    if [[ "$CHECK" -eq 0 ]]; then
      mkdir -p "$(dirname "$skill")"
      printf "%s\n" "$skill_body" > "$skill"
      skills_generated=$((skills_generated + 1))
    fi
  fi

  consumer="$CONSUMER_DIR/devspark-$cmd/SKILL.md"
  consumer_body="$(consumer_skill_body "$cmd" "$description")"
  if [[ ! -f "$consumer" ]] || ! cmp -s <(printf "%s\n" "$consumer_body") "$consumer"; then
    consumer_drift+=("devspark-$cmd")
    if [[ "$CHECK" -eq 0 ]]; then
      mkdir -p "$(dirname "$consumer")"
      printf "%s\n" "$consumer_body" > "$consumer"
      consumer_generated=$((consumer_generated + 1))
    fi
  fi
done

# Generator-owned skill folders with no command template are reported, never deleted.
for d in "$SKILLS_DIR"/devspark-*/; do
  name="$(basename "$d")"
  [[ -f "$COMMANDS_DIR/${name#devspark-}.md" ]] || orphans+=("$name")
done
for d in "$CONSUMER_DIR"/devspark-*/; do
  name="$(basename "$d")"
  [[ -f "$COMMANDS_DIR/${name#devspark-}.md" ]] || consumer_orphans+=("$name")
done

if [[ "$CHECK" -eq 1 ]]; then
  failed=0
  if [[ ${#skill_drift[@]} -gt 0 ]]; then
    echo "Skill entry-point drift detected for ${#skill_drift[@]} skill(s):"
    for d in "${skill_drift[@]}"; do echo "  - $d"; done
    failed=1
  fi
  if [[ ${#consumer_drift[@]} -gt 0 ]]; then
    echo "Consumer skill drift detected for ${#consumer_drift[@]} skill(s):"
    for d in "${consumer_drift[@]}"; do echo "  - $d"; done
    failed=1
  fi
  if [[ ${#orphans[@]} -gt 0 ]]; then
    echo "Orphaned skill entry point(s) with no command template:"
    for d in "${orphans[@]}"; do echo "  - $d"; done
    failed=1
  fi
  if [[ ${#consumer_orphans[@]} -gt 0 ]]; then
    echo "Orphaned consumer skill(s) with no command template:"
    for d in "${consumer_orphans[@]}"; do echo "  - $d"; done
    failed=1
  fi
  if [[ "$failed" -eq 1 ]]; then
    echo ""
    echo "Run scripts/bash/generate-atomic-shims.sh to regenerate; remove orphaned skill folders manually."
    exit 1
  fi
  echo "No skill drift detected."
  exit 0
fi

echo "Generated/updated ${skills_generated} source skill(s) under .github/skills/."
echo "Generated/updated ${consumer_generated} consumer skill(s) under templates/consumer-skills/."
if [[ ${#orphans[@]} -gt 0 || ${#consumer_orphans[@]} -gt 0 ]]; then
  echo "Orphaned skill(s) with no command template (remove manually):" >&2
  for d in ${orphans[@]+"${orphans[@]}"}; do echo "  - $d" >&2; done
  for d in ${consumer_orphans[@]+"${consumer_orphans[@]}"}; do echo "  - $d" >&2; done
  exit 1
fi
exit 0
