#!/usr/bin/env pwsh
# BSW.DevSpark - (c) 2026 Baylor Scott & White Health. Source: https://bsw-devspark.bswhive.com
<#
.SYNOPSIS
    Generate the Agent Skills for every templates/commands/*.md: the source-repository
    skills and the published consumer skills.

.DESCRIPTION
    For each command in templates/commands/, writes .github/skills/devspark-<command>/SKILL.md,
    a thin entry point whose description comes from the command template and whose body routes
    directly to templates/commands/<command>.md. The five source-only commands carry the stop
    body from eng/skills/source-stop/<command>.md instead. No command instructions are copied
    into a skill.

    It also writes templates/consumer-skills/devspark-<command>/SKILL.md, the published
    consumer skill: a thin entry point that resolves the command through the
    developer > team > default chain.

    Exit codes:
        0 - success (no drift, or skills (re)generated)
        1 - drift detected with -Check (CI gate)
        2 - I/O failure
#>
[CmdletBinding()]
param(
    [switch]$Check,
    [string]$RepoRoot
)

if (-not $RepoRoot) {
    $RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path
}

$commandsDir = Join-Path $RepoRoot "templates/commands"
$stopDir = Join-Path $RepoRoot "eng/skills/source-stop"
$skillsDir = Join-Path $RepoRoot ".github/skills"
$consumerDir = Join-Path $RepoRoot "templates/consumer-skills"
$sourceOnlyCommands = @('add-application', 'discover-constitution', 'list-applications', 'personalize', 'upgrade')

if (-not (Test-Path $commandsDir)) {
    Write-Error "commands dir not found: $commandsDir"; exit 2
}

function Read-NormalizedLines([string]$Path) {
    [IO.File]::ReadAllText($Path).Replace("`r`n", "`n") -split "`n"
}

function Get-TemplateDescription([string]$Path) {
    foreach ($line in Read-NormalizedLines $Path) {
        if ($line -match '^description:[ \t]*(.*?)[ \t]*$') { return $Matches[1] }
    }
    return ''
}

# Source-repository skill: the template description plus either a direct route to the command
# template or, for the source-only commands, the stop body.
function Get-SourceSkillBody([string]$Command, [string]$Description) {
    if ($sourceOnlyCommands -contains $Command) {
        $comment = "<!-- Generated by scripts/{bash,powershell}/generate-atomic-shims from templates/commands/$Command.md (description) and eng/skills/source-stop/$Command.md (stop). Do not edit; edit the sources and regenerate. -->"
        $routing = [IO.File]::ReadAllText((Join-Path $stopDir "$Command.md")).Replace("`r`n", "`n").TrimEnd("`n")
    } else {
        $comment = "<!-- Generated by scripts/{bash,powershell}/generate-atomic-shims from templates/commands/$Command.md (description). Do not edit; edit the source and regenerate. -->"
        $routing = "Read and follow the instructions in ``templates/commands/$Command.md`` exactly."
    }
    return (@(
        '---'
        "name: devspark-$Command"
        "description: `"$Description`""
        'user-invocable: true'
        'disable-model-invocation: true'
        '---'
        ''
        $comment
        ''
        $routing
    ) -join "`n") + "`n"
}

$commands = @(Get-ChildItem -Path $commandsDir -Filter "*.md" | Sort-Object Name)

# Published consumer skill: a thin entry point that resolves the command through the
# developer > team > default chain and passes the typed text through as the command input.
function Get-ConsumerSkillBody([string]$Command, [string]$Description) {
    $text = @"
---
name: devspark-$Command
description: "$Description"
user-invocable: true
disable-model-invocation: true
---

<!-- Generated by BSW.DevSpark. Do not edit. -->

## Prompt Resolution

Determine the current git user by running ``git config user.name``.
Normalize to a folder-safe slug: lowercase, replace spaces with hyphens, strip non-alphanumeric/hyphen chars.

Read and execute the instructions from the **first file that exists**:

1. ``.devspark.work/{git-user}/commands/devspark.$Command.md`` (personalized override)
2. ``.devspark.work/commands/devspark.$Command.md`` (team customization)
3. ``.devspark/defaults/commands/devspark.$Command.md`` (stock default)

Where ``{git-user}`` is the normalized slug from the step above.

## User Input

The text typed after ``/devspark-$Command`` is the command input. Pass it unchanged to the resolved prompt.
"@
    return $text.Replace("`r`n", "`n").TrimEnd("`n") + "`n"
}

# Validate every source before writing anything, so a bad source never leaves partial output.
foreach ($command in $commands) {
    if (-not (Get-TemplateDescription $command.FullName)) {
        Write-Error "command template has no description: $($command.FullName)"; exit 2
    }
}
foreach ($cmd in $sourceOnlyCommands) {
    if ((Test-Path -LiteralPath (Join-Path $commandsDir "$cmd.md")) -and -not (Test-Path -LiteralPath (Join-Path $stopDir "$cmd.md"))) {
        Write-Error "missing source-only stop body: $(Join-Path $stopDir "$cmd.md")"; exit 2
    }
}

$skillDrift = @()
$consumerDrift = @()
$orphans = @()
$consumerOrphans = @()
$skillsGenerated = 0
$consumerGenerated = 0
$utf8 = [Text.UTF8Encoding]::new($false)

$commands | ForEach-Object {
    $cmd = $_.BaseName

    $description = (Get-TemplateDescription $_.FullName).Replace('\', '\\').Replace('"', '\"')
    $skill = Join-Path $skillsDir "devspark-$cmd/SKILL.md"
    $skillBody = Get-SourceSkillBody $cmd $description

    if (-not (Test-Path -LiteralPath $skill) -or [IO.File]::ReadAllText($skill) -cne $skillBody) {
        $skillDrift += "devspark-$cmd"
        if (-not $Check) {
            New-Item -ItemType Directory -Force -Path (Split-Path $skill) | Out-Null
            [IO.File]::WriteAllText($skill, $skillBody, $utf8)
            $skillsGenerated += 1
        }
    }

    $consumer = Join-Path $consumerDir "devspark-$cmd/SKILL.md"
    $consumerBody = Get-ConsumerSkillBody $cmd $description
    if (-not (Test-Path -LiteralPath $consumer) -or [IO.File]::ReadAllText($consumer) -cne $consumerBody) {
        $consumerDrift += "devspark-$cmd"
        if (-not $Check) {
            New-Item -ItemType Directory -Force -Path (Split-Path $consumer) | Out-Null
            [IO.File]::WriteAllText($consumer, $consumerBody, $utf8)
            $consumerGenerated += 1
        }
    }
}

# Generator-owned skill folders with no command template are reported, never deleted.
if (Test-Path -LiteralPath $skillsDir) {
    Get-ChildItem -LiteralPath $skillsDir -Directory -Filter 'devspark-*' | Sort-Object Name | ForEach-Object {
        if (-not (Test-Path -LiteralPath (Join-Path $commandsDir "$($_.Name.Substring('devspark-'.Length)).md"))) {
            $orphans += $_.Name
        }
    }
}
if (Test-Path -LiteralPath $consumerDir) {
    Get-ChildItem -LiteralPath $consumerDir -Directory -Filter 'devspark-*' | Sort-Object Name | ForEach-Object {
        if (-not (Test-Path -LiteralPath (Join-Path $commandsDir "$($_.Name.Substring('devspark-'.Length)).md"))) {
            $consumerOrphans += $_.Name
        }
    }
}

if ($Check) {
    $failed = $false
    if ($skillDrift.Count -gt 0) {
        Write-Host "Skill entry-point drift detected for $($skillDrift.Count) skill(s):"
        $skillDrift | ForEach-Object { Write-Host "  - $_" }
        $failed = $true
    }
    if ($consumerDrift.Count -gt 0) {
        Write-Host "Consumer skill drift detected for $($consumerDrift.Count) skill(s):"
        $consumerDrift | ForEach-Object { Write-Host "  - $_" }
        $failed = $true
    }
    if ($orphans.Count -gt 0) {
        Write-Host "Orphaned skill entry point(s) with no command template:"
        $orphans | ForEach-Object { Write-Host "  - $_" }
        $failed = $true
    }
    if ($consumerOrphans.Count -gt 0) {
        Write-Host "Orphaned consumer skill(s) with no command template:"
        $consumerOrphans | ForEach-Object { Write-Host "  - $_" }
        $failed = $true
    }
    if ($failed) {
        Write-Host ""
        Write-Host "Run scripts/powershell/generate-atomic-shims.ps1 to regenerate; remove orphaned skill folders manually."
        exit 1
    }
    Write-Host "No skill drift detected."
    exit 0
}

Write-Host "Generated/updated $skillsGenerated source skill(s) under .github/skills/."
Write-Host "Generated/updated $consumerGenerated consumer skill(s) under templates/consumer-skills/."
if ($orphans.Count -gt 0 -or $consumerOrphans.Count -gt 0) {
    Write-Host "Orphaned skill(s) with no command template (remove manually):"
    @($orphans) + @($consumerOrphans) | ForEach-Object { Write-Host "  - $_" }
    exit 1
}
exit 0
